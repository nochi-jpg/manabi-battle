# ---- 異分母の分数のたし算・ひき算 ----
for a, b in [(F(1, 6), F(3, 4)), (F(2, 9), F(1, 6)), (F(3, 10), F(5, 6)), (F(1, 2), F(7, 10))]:
    v = a + b
    wr = [fr(F(a.numerator + b.numerator, a.denominator + b.denominator)), fr(v + F(1, v.denominator)), fr(F(a.numerator * b.denominator + b.numerator, a.denominator * b.denominator))]
    add(f'{fr(a)} ＋ {fr(b)} = ？', opts(fr(v), wr + [fr(v * 2)]), '通分してから分子どうしをたす。答えは約分する。')
for a, b in [(F(5, 6), F(1, 3)), (F(7, 12), F(1, 4)), (F(9, 10), F(2, 5)), (F(4, 5), F(1, 2))]:
    v = a - b
    wr = [fr(F(abs(a.numerator - b.numerator), abs(a.denominator - b.denominator) or 1)), fr(v + F(1, v.denominator)), fr(v * 2), fr(v / 2)]
    add(f'{fr(a)} − {fr(b)} = ？', opts(fr(v), wr), '通分してから分子どうしをひく。答えは約分する。')
