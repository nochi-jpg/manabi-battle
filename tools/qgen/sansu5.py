def add(t, a, x): Q.append(('算数', 5, t, a, x))
def opts(ans, wrong):
    w = []
    for v in wrong:
        if v is not None and v != ans and v not in w: w.append(v)
    assert len(w) >= 3, (ans, wrong)
    return [ans] + w[:3]
def dec(v): return f'{float(v):.4f}'.rstrip('0').rstrip('.')
def fr(v):
    v = F(v); return str(v.numerator) if v.denominator == 1 else f'{v.numerator}/{v.denominator}'
def lcm(a, b): return a * b // gcd(a, b)

