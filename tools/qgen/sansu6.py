def add(t, a, x): Q.append(('算数', 6, t, a, x))
def fr(v):
    v = F(v); return str(v.numerator) if v.denominator == 1 else f'{v.numerator}/{v.denominator}'
def opts(ans, wrong):
    w = []
    for v in wrong:
        if v is not None and v != ans and v not in w: w.append(v)
    assert len(w) >= 3, (ans, wrong)
    return [ans] + w[:3]

