from fractions import Fraction as F
Q = []
def add(t, a, x): Q.append(('算数', 4, t, a, x))
def opts(ans, wrong):
    w = []
    for v in wrong:
        if v != ans and v not in w: w.append(v)
    assert len(w) >= 3, (ans, wrong)
    return [ans] + w[:3]
def n(v): return f'{v:,}'.replace(',', '') if isinstance(v, int) else str(v)
def dec(v):  # 小数を きれいな文字に
    s = f'{v:.4f}'.rstrip('0').rstrip('.')
    return s

